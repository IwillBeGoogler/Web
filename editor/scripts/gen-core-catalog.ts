// Writes core/catalog.generated.ts: a slim (id, label, aliases, tags) view of the icon catalog that the server
// (MCP search_catalog, DSL icon resolution) and the client share. Run: cd server && npx tsx ../scripts/gen-core-catalog.ts
import { writeFileSync } from 'node:fs';
import { CATALOG_DEFS } from '../src/data/catalog.generated';
import * as aws from '../src/data/icons/cloud/aws.generated';
import * as gcp from '../src/data/icons/cloud/gcp.generated';
import * as azure from '../src/data/icons/cloud/azure.generated';
import * as k8s from '../src/data/icons/cloud/k8s.generated';
import * as ibm from '../src/data/icons/cloud/ibm.generated';
import * as clouds from '../src/data/icons/cloud/clouds.generated';
import * as cncf from '../src/data/icons/cloud/cncf.generated';
import { PROFILES } from '../src/clusters/profiles';

type Row = [id: string, label: string, aliases: string[], tags: string[], group: 0 | 1];
const rows = new Map<string, Row>();
for (const d of CATALOG_DEFS) rows.set(d.id, [d.id, d.label, d.aliases, d.tags, 0]);
for (const p of [aws, gcp, azure, k8s, ibm, clouds, cncf])
  for (const d of p.DEFS) {
    const prev = rows.get(d.id);
    if (prev) prev[3] = [...new Set([...prev[3], ...d.tags])];
    else rows.set(d.id, [d.id, d.label, d.aliases, d.tags, d.kind === 'group' ? 1 : 0]);
  }
const clusters = PROFILES.map((p) => [p.id, p.label, p.tech, p.iconId, p.topologies]);
const out = `// GENERATED by scripts/gen-core-catalog.ts - do not edit.\nexport type CatalogRow = [id: string, label: string, aliases: string[], tags: string[], group: 0 | 1];\nexport const CATALOG_ROWS: CatalogRow[] = ${JSON.stringify([...rows.values()])};\nexport type ClusterRow = [profileId: string, label: string, tech: string, iconId: string, topologies: string[]];\nexport const CLUSTER_ROWS: ClusterRow[] = ${JSON.stringify(clusters)};\n`;
writeFileSync(new URL('../core/catalog.generated.ts', import.meta.url), out);
console.log('rows', rows.size, 'bytes', out.length);
