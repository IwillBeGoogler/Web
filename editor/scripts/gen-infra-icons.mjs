const dropped = [];
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const pick = (set, id, fb, ctx) => {
  if (!set.has(id)) { dropped.push(`${ctx}: ${id}`); return undefined; }
  return [id, fb];
};
const rules = [];
const counts = { aws: 0, azure: 0, gcp: 0, ibm: 0, oci: 0, alicloud: 0, digitalocean: 0 };
const push = (provider, match, icons) => { rules.push({ match, icons }); counts[provider]++; };
const longest = (s) => Math.max(...s.split(',').map((x) => x.length));

for (const [tf, cfn, id, fb] of [...AWS].sort((a, b) => longest(b[0]) - longest(a[0]))) {
  const icons = pick(known.aws, id, fb, 'aws');
  if (!icons) continue;
  const tfAlt = tf.split(',').map(esc).join('|');
  const cfnAlt = (cfn === '=' ? tf : cfn).split(',').map((x) => (x.includes('::') ? esc(x) : esc(x) + '::\\w+'));
  push('aws', `^(aws_(${tfAlt})(_\\w+)?|aws::(${cfnAlt.join('|')}))$`, icons);
}
for (const [list, id, fb] of [...AZURE].sort((a, b) => longest(b[0]) - longest(a[0]))) {
  const icons = pick(known.azure, id, fb, 'azure');
  if (icons) push('azure', `^azurerm_(${list.split(',').map(esc).join('|')})(_\\w+)?$`, icons);
}
for (const [list, id, fb] of [...GCP].sort((a, b) => longest(b[0]) - longest(a[0]))) {
  const icons = pick(known.gcp, id, fb, 'gcp');
  if (icons) push('gcp', `^google_(${list.split(',').map(esc).join('|')})(_\\w+)?$`, icons);
}

for (const [list, id, fb] of [...IBM].sort((a, b) => longest(b[0]) - longest(a[0]))) {
  const icons = pick(known.ibm, id, fb, 'ibm');
  if (icons) push('ibm', `^ibm_(${list.split(',').map(esc).join('|')})(_\\w+)?$`, icons);
}
const logo = (id) => (all.has(id) ? [id] : []);
for (const [prefix, table, logoId] of [['oci', OCI, 'platforms-oracle-cloud-infrastructure'], ['alicloud', ALICLOUD, 'alibaba-cloud'], ['digitalocean', DO, 'digitalocean']]) {
  for (const [list, generic] of [...table].sort((a, b) => longest(b[0]) - longest(a[0])))
    push(prefix, `^${prefix}_(${list.split(',').map(esc).join('|')})(_\\w+)?$`, [generic, ...logo(logoId)]);
  push(prefix, `^${prefix}_\\w+$`, [...logo(logoId), 'service']); // any other resource: provider logo
}

const body = rules.map((r) => `  { match: ${JSON.stringify(r.match)}, icons: ${JSON.stringify(r.icons)} },`).join('\n');
