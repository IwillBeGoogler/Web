import { createHash } from 'node:crypto';
import { ALL_TEMPLATES, type Template } from './index';

/**
 * Builds the goose migration that seeds the backend template gallery (dg_templates) from the built-in templates.
 * Regenerate after adding templates: `SEED_OUT=<migration path> npx vitest run src/templates/seedSql.test.ts` (from Web/editor).
 * Board templates have no gallery lens and are left out.
 */

export type GalleryKind = 'system' | 'db' | 'ood';

export const SEED_PROJECT = `prj_${hex('builtin-template-gallery')}`;
const SEED_TIME = Date.UTC(2026, 10, 16);
const POSITION_BASE = 1000;

function hex(s: string): string {
  return createHash('md5').update(s).digest('hex').slice(0, 16);
}

export function galleryKind(t: Template): GalleryKind | null {
  if (t.id.startsWith('board-')) return null;
  if (t.id.startsWith('er-') || t.id.startsWith('db-')) return 'db';
  if (t.id.startsWith('uml-') || t.id.startsWith('lld-') || t.tags?.includes('uml')) return 'ood';
  return 'system';
}

const FILE_KIND: Record<GalleryKind, string> = { system: 'sdd', db: 'erd', ood: 'uml' };

export interface SeedRow {
  templateId: string;
  fileId: string;
  versionId: string;
  title: string;
  kind: GalleryKind;
  description: string;
  position: number;
  data: Record<string, unknown>;
}

export function seedRows(templates: Template[] = ALL_TEMPLATES): SeedRow[] {
  const rows: SeedRow[] = [];
  for (const t of templates) {
    const kind = galleryKind(t);
    if (!kind) continue;
    const d = t.build();
    const fileId = `fil_${hex(`tpl-file:${t.id}`)}`;
    const page = `pg_${hex(`tpl-page:${t.id}`).slice(0, 8)}`;
    rows.push({
      templateId: `tpl_${hex(`tpl:${t.id}`)}`,
      fileId,
      versionId: `ver_${hex(`tpl-ver:${t.id}`)}`,
      title: t.name.slice(0, 120),
      kind,
      description: (t.description ?? '').slice(0, 500),
      position: POSITION_BASE + rows.length,
      data: {
        version: 2, id: fileId, name: t.name, createdAt: SEED_TIME, updatedAt: SEED_TIME, activePageId: page,
        pages: [{ id: page, name: t.name, nodes: d.nodes, edges: d.edges }],
      },
    });
  }
  return rows;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
/** dollar-quoted JSON: the tag cannot appear inside, so no escaping is needed */
function jsonb(v: unknown): string {
  const s = JSON.stringify(v);
  if (s.includes('$tpl$')) throw new Error('template JSON contains the dollar-quote tag');
  return `$tpl$${s}$tpl$::jsonb`;
}

export function templateSeedSql(templates: Template[] = ALL_TEMPLATES): string {
  const rows = seedRows(templates);
  const exists = (table: string, id: string) => `WHERE EXISTS (SELECT 1 FROM ${table} WHERE id = ${q(id)})`;
  const out: string[] = [
    '-- +goose Up',
    '-- Built-in diagram templates in the public gallery (system design, database, OOD/UML).',
    '-- GENERATED by Web/editor/src/templates/seedSql.ts; do not edit by hand.',
    '-- Owner is the first account (the bootstrap super admin; roles live in Guard, not in users); with no user yet',
    '-- nothing is seeded (re-run after creating one:',
    '-- every statement is idempotent by fixed ids). Admins can unpublish or reorder entries in the admin panel.',
    `INSERT INTO dg_projects (id, owner_id, name)`,
    `SELECT ${q(SEED_PROJECT)}, id, 'Template gallery' FROM users ORDER BY id LIMIT 1`,
    `ON CONFLICT (id) DO NOTHING;`,
    '',
  ];
  for (const r of rows) {
    out.push(
      `-- ${r.title}`,
      `INSERT INTO dg_files (id, project_id, name, kind, file_kind, position, data, version, page_count)`,
      `SELECT ${q(r.fileId)}, ${q(SEED_PROJECT)}, ${q(r.title)}, ${q(FILE_KIND[r.kind])}, ${q(r.kind)}, ${r.position}, ${jsonb(r.data)}, 1, 1`,
      `${exists('dg_projects', SEED_PROJECT)} ON CONFLICT (id) DO NOTHING;`,
      `INSERT INTO dg_file_versions (id, file_id, version, name, data)`,
      `SELECT ${q(r.versionId)}, id, 1, name, data FROM dg_files WHERE id = ${q(r.fileId)} ON CONFLICT (id) DO NOTHING;`,
      `INSERT INTO dg_templates (id, title, kind, description, file_id, published, position)`,
      `SELECT ${q(r.templateId)}, ${q(r.title)}, ${q(r.kind)}, ${q(r.description)}, ${q(r.fileId)}, true, ${r.position}`,
      `${exists('dg_files', r.fileId)} ON CONFLICT (id) DO NOTHING;`,
      '',
    );
  }
  out.push('-- +goose Down', `DELETE FROM dg_projects WHERE id = ${q(SEED_PROJECT)};`, '');
  return out.join('\n');
}
