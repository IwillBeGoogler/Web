/** the canvas colour a file's own (project-level) settings set, if any */
const pageBackground = (doc: { settings?: { canvas?: { background?: string } } } | null): string | undefined => doc?.settings?.canvas?.background;

/** Legacy label kept for the existing tests / other callers. */
export function formatUpdated(ts: number, now = Date.now()): string {
  const d = Math.max(0, now - ts);
  const min = Math.floor(d / 60000);
  if (min < 1) return t('just now');
  if (min < 60) return t('{n} min ago', { n: min });
  const h = Math.floor(min / 60);
  if (h < 24) return t('{n} h ago', { n: h });
  const days = Math.floor(h / 24);
  if (days < 30) return t('{n} d ago', { n: days });
  return new Date(ts).toLocaleDateString();
}

const VIEW_KEY = 'sdd:home-view';
const SORT_KEY = 'sdd:home-sort';
const read = <T extends string>(key: string, ok: T[], dflt: T): T => {
  try {
    const v = localStorage.getItem(key) as T | null;
    return v && ok.includes(v) ? v : dflt;
  } catch {
    return dflt;
  }
};

/** Thumbnails are built one per tick so the page paints skeletons first, then fills in. */
function useThumbs(keys: string[], build: (key: string) => string): Map<string, string> {
  const [done, setDone] = useState<Map<string, string>>(new Map());
  const buildRef = useRef(build);
  buildRef.current = build;
  const joined = keys.join('|');
  useEffect(() => {
    let cancelled = false;
    const todo = keys.filter((k) => !done.has(k));
    if (!todo.length) return;
    const t = setTimeout(() => {
      if (cancelled) return;
      const next = new Map(done);
      for (const k of todo.slice(0, 3)) next.set(k, buildRef.current(k));
      setDone(next);
    }, 0);
    return () => {
      cancelled = true;
      clearTimeout(t);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [joined, done]);
  return done;
}

function Thumb({ svg, src, id }: { svg?: string; src?: string; id?: string }) {
  if (src) return <div className="project-thumb"><img src={src} alt="" loading="lazy" decoding="async" data-testid={`thumb-img-${id}`} style={{ width: '100%', height: '100%', objectFit: 'cover' }} /></div>;
  if (!svg) return <div className="project-thumb skeleton" aria-hidden data-testid="thumb-skeleton" />;
  // svg is generated by buildThumbnail (numbers + fixed attributes only)
  return <div className="project-thumb" dangerouslySetInnerHTML={{ __html: svg }} />;
}

