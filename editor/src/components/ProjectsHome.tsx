/** a project as the home page shows it */
interface Card extends WsProject {
  fileCount: number;
  folderCount: number;
  pageCount: number;
  firstFileId: string | null;
}
const readCards = (): Card[] => listWsProjects(localStorage).map((p) => ({ ...p, ...projectStats(localStorage, p.id) }));

export function ProjectsHome({ onOpen }: { onOpen: (id: string) => void }) {
  const [list, setList] = useState<Card[]>(readCards);
  const projRef = useRef<HTMLInputElement>(null);
  const [menu, setMenu] = useState<{ x: number; y: number; id: string } | null>(null);
  const [query, setQuery] = useState('');
  const [view, setView] = useState<'grid' | 'list'>(() => read(VIEW_KEY, ['grid', 'list'], 'grid'));
  const [sort, setSort] = useState<SortKey>(() => read(SORT_KEY, ['updated', 'name'], 'updated'));
  const setSettingsOpen = useUiStore((s) => s.setSettingsOpen);
  const searchRef = useRef<HTMLInputElement>(null);
  const sdd = useSddActions();
  const refresh = useCallback(() => setList(readCards()), []);
  const rev = useLibrary((s) => s.rev);
  useEffect(refresh, [refresh, rev]);
  useEffect(() => {
    try {
      localStorage.setItem(VIEW_KEY, view);
      localStorage.setItem(SORT_KEY, sort);
    } catch {
      /* ignore */
    }
  }, [view, sort]);
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') {
        e.preventDefault();
        searchRef.current?.focus();
        return;
      }
      // N: new project dialog (ignored while typing, with modifiers, or while a dialog is open)
      const t = e.target as HTMLElement | null;
      const typing = !!t && (t.isContentEditable || ['INPUT', 'TEXTAREA', 'SELECT'].includes(t.tagName));
      if (e.key.toLowerCase() === 'n' && !e.metaKey && !e.ctrlKey && !e.altKey && !e.shiftKey && !typing && !e.repeat && !useDialogStore.getState().stack.length) {
        e.preventDefault();
        startNewRef.current();
      }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, []);

  const visible = useMemo(() => sortProjects(filterProjects(list, query), sort), [list, query, sort]);
  const thumbs = useThumbs(list.map((p) => `${p.id}:${p.updatedAt}`), (key) => {
    const card = list.find((p) => `${p.id}:${p.updatedAt}` === key);
    const full = card?.firstFileId ? loadFile(localStorage, card.firstFileId) : null;
    const page = full?.pages.find((pg) => pg.id === full.activePageId) ?? full?.pages[0];
    return buildThumbnail(page?.nodes ?? [], page?.edges ?? [], { width: 240, height: 150 }, 10, pageBackground(full));
  });
  const tplThumbs = useThumbs(ALL_TEMPLATES.map((t) => t.id), (id) => {
    const d = ALL_TEMPLATES.find((t) => t.id === id)!.build();
    return buildThumbnail(d.nodes, d.edges, { width: 280, height: 170 }, 10, d.settings?.canvas?.background);
  });

  const canRename = (id: string) => canEdit(getProjectSync(localStorage, id)?.role ?? 'owner');
  const rename = async (id: string) => {
    const p = list.find((x) => x.id === id);
    if (!p || !canRename(id)) return;
    const name = await renameProjectDialog(p.name);
    if (name === null) return;
    renameWsProject(localStorage, id, name);
    if (getProjectSync(localStorage, id)) {
      enqueue(localStorage, id, { t: 'renameProject', name: name.trim() });
      requestTreeSync(id, 0);
    }
    refresh();
  };
  const duplicate = async (id: string) => {
    const p = list.find((x) => x.id === id);
    if (!p) return;
    const name = await duplicateProjectDialog(p.name);
    if (name === null) return;
    duplicateWsProject(localStorage, id, name);
    refresh();
    toast.success(t('Project duplicated'));
  };
  const remove = async (id: string) => {
    const p = list.find((x) => x.id === id);
    if (!p || !(await deleteProjectDialog(p.name, p.fileCount))) return;
    if (getProjectSync(localStorage, id) && useSession.getState().mode === 'server') {
      try {
        await api.deleteProject(id);
      } catch (e) {
        // only the owner can delete on the server; without a connection nothing is removed so the two sides stay consistent
        toast.error(e instanceof Error ? t('Not deleted: {error}', { error: e.message }) : t('Not deleted'));
        return;
      }
    }
    deleteWsProject(localStorage, id);
    refresh();
  };
  const actions = {
    open: onOpen,
    rename: (id: string) => void rename(id),
    canRename,
    duplicate: (id: string) => void duplicate(id),
    remove: (id: string) => void remove(id),
    export: (id: string) => {
      const p = list.find((x) => x.id === id);
      if (!p) return toast.error(t('Project not found'));
      downloadBlob(exportProjectBytes(localStorage, id), exportFileName(p.name, 'sdd'), 'application/vnd.sdd+zip');
      toast.success(t('Exported .sdd'));
    },
  };
  const importProject = async (file: File) => {
    try {
      await sdd.openBytes(new Uint8Array(await file.arrayBuffer()), file.name); // sniffs: project container, file container or text
      refresh();
    } catch (e) {
      toast.error(e instanceof SddError ? t('Could not import {file}: {error}', { file: file.name, error: e.message }) : t('Import failed: {error}', { error: e instanceof Error ? e.message : String(e) }));
    }
  };
  const startNewRef = useRef<() => void>(() => {});
  const startNew = async () => {
    const r = await newProjectDialog(ALL_TEMPLATES.map((t) => ({ id: t.id, name: t.name })));
    if (!r) return;
    const tpl = r.templateId ? ALL_TEMPLATES.find((t) => t.id === r.templateId) : undefined;
    const { project } = createWsProject(localStorage, r.name, tpl ? { content: tpl.build(), pageName: tpl.name } : {});
    onOpen(project.id);
  };
  startNewRef.current = () => void startNew();
  const stagger = (i: number) => ({ initial: { opacity: 0, y: 10 }, animate: { opacity: 1, y: 0 }, transition: { delay: Math.min(i, 8) * 0.04, type: 'spring' as const, stiffness: 380, damping: 32 } });

  return (
    <main className="home">
      <div className="home-inner">
        <header className="home-topbar">
          <span className="brand"><HomeLink size={26} wordmark /></span>
          <span className="spacer" />
          <button type="button" className="home-cmdk" aria-keyshortcuts="Meta+K Control+K" onClick={() => searchRef.current?.focus()}>
            <Search size={14} aria-hidden /> <span>{t('Search')}</span> <kbd><Command size={10} aria-hidden />K</kbd>
          </button>
          <ThemeToggle />
          <IconButton label={t('Settings')} onClick={() => setSettingsOpen(true)}><SettingsIcon size={16} aria-hidden /></IconButton>
          <UserMenu />
        </header>
        <UploadBanner />

        <motion.section className="hero" {...stagger(0)}>
          <div>
            <h1>{greeting()}</h1>
            <p>{t('Organise architecture diagrams, data models and boards in projects of files. Each file is one canvas. Everything is saved in your browser.')}</p>
          </div>
          <div className="hero-actions">
            <button type="button" className="btn btn-primary primary" onClick={() => void startNew()}><Plus size={14} aria-hidden /> {t('New project')}</button>
            <button type="button" className="btn" onClick={() => void sdd.open()}><FileUp size={14} aria-hidden /> {t('Open .sdd')}</button>
            <button type="button" className="btn" onClick={() => projRef.current?.click()}><FileUp size={14} aria-hidden /> {t('Import project')}</button>
            <input ref={projRef} type="file" accept={OPEN_ACCEPT} hidden data-testid="import-project-input" onChange={(e) => { const f = e.target.files?.[0]; if (f) void importProject(f); e.target.value = ''; }} />
          </div>
        </motion.section>

        <motion.section aria-labelledby="tpl-h" {...stagger(1)}>
          <h2 className="section-title" id="tpl-h">{t('Start from a template')}</h2>
          <ul className="tpl-row" aria-label={t('Templates')}>
            {ALL_TEMPLATES.map((tp) => (
              <li key={tp.id}>
                <button
                  type="button"
                  className="project-card template-card"
                  aria-label={t('Use template {name}', { name: t(tp.name) })}
                  onClick={() => {
                    onOpen(createWsProject(localStorage, tp.name, { content: tp.build(), pageName: tp.name }).project.id);
                  }}
                >
                  <Thumb svg={tplThumbs.get(tp.id)} />
                  <div className="project-body"><strong>{t(tp.name)}</strong></div>
                </button>
              </li>
            ))}
          </ul>
        </motion.section>

        <motion.section aria-labelledby="recent-h" {...stagger(2)}>
          <div className="home-tools">
            <h2 className="section-title" id="recent-h">{t('Recent projects')}</h2>
            <span className="spacer" />
            <div className="search-wrap">
              <Search size={14} aria-hidden />
              <input ref={searchRef} type="search" placeholder={t('Filter projects…')} aria-label={t('Search projects')} value={query} onChange={(e) => setQuery(e.target.value)} />
            </div>
            <div className="seg" role="group" aria-label={t('Sort')}>
              <button type="button" className={sort === 'updated' ? 'active' : ''} aria-pressed={sort === 'updated'} aria-label={t('Sort by last edited')} title={t('Last edited')} onClick={() => setSort('updated')}><Clock size={14} aria-hidden /></button>
              <button type="button" className={sort === 'name' ? 'active' : ''} aria-pressed={sort === 'name'} aria-label={t('Sort by name')} title={t('Name')} onClick={() => setSort('name')}><ArrowDownAZ size={14} aria-hidden /></button>
            </div>
            <div className="seg" role="group" aria-label={t('View')}>
              <button type="button" className={view === 'grid' ? 'active' : ''} aria-pressed={view === 'grid'} aria-label={t('Grid view')} onClick={() => setView('grid')}><LayoutGrid size={14} aria-hidden /></button>
              <button type="button" className={view === 'list' ? 'active' : ''} aria-pressed={view === 'list'} aria-label={t('List view')} onClick={() => setView('list')}><List size={14} aria-hidden /></button>
            </div>
          </div>

          {list.length === 0 ? (
            <>
              <p className="muted home-empty-hint"><strong>{t('No projects yet')}</strong> <span>{t('Start blank, or begin from a template.')}</span></p>
              <ul className="project-grid" aria-label={t('Start a project')}>
                <BlankCard onClick={() => void startNew()} />
                {ALL_TEMPLATES.slice(0, 3).map((tp) => (
                  <li key={tp.id} className="project-card template-card">
                    <button type="button" className="template-suggest" onClick={() => onOpen(createWsProject(localStorage, tp.name, { content: tp.build(), pageName: tp.name }).project.id)}>
                      <Thumb svg={tplThumbs.get(tp.id)} />
                      <div className="project-body"><strong>{t(tp.name)}</strong><div className="muted">{t('Template')}</div></div>
                    </button>
                  </li>
                ))}
              </ul>
            </>
          ) : (
            <ul className={`project-grid${view === 'list' ? ' list' : ''}`}>
              {view === 'grid' && <BlankCard onClick={() => void startNew()} />}
              {visible.map((p, i) => (
                <motion.li
                  key={p.id}
                  className="project-card"
                  data-testid={`project-${p.id}`}
                  {...stagger(i)}
                  whileHover={{ y: -3 }}
                  onContextMenu={(e) => { e.preventDefault(); setMenu({ x: e.clientX, y: e.clientY, id: p.id }); }}
                >
                  <Thumb svg={thumbs.get(`${p.id}:${p.updatedAt}`)} src={p.thumbnailUrl} id={p.id} />
                  <div className="project-body">
                    <div className="project-meta">
                      <button type="button" className="project-open" onClick={() => onOpen(p.id)} onDoubleClick={() => void rename(p.id)} title={canRename(p.id) ? t('Double-click to rename') : undefined}>{p.name}</button>
                      <div className="muted project-counts" data-testid={`counts-${p.id}`}>{t(p.fileCount === 1 ? '{n} file · edited {when}' : '{n} files · edited {when}', { n: p.fileCount, when: formatRelative(p.updatedAt) })}</div>
                    </div>
                    <div className="project-actions">
                      <IconButton label={t('Open')} onClick={() => onOpen(p.id)}><ExternalLink size={14} aria-hidden /></IconButton>
                      {canRename(p.id) && <IconButton label={t('Rename')} onClick={() => void rename(p.id)}><Pencil size={14} aria-hidden /></IconButton>}
                      <IconButton label={t('Duplicate')} onClick={() => void duplicate(p.id)}><Copy size={14} aria-hidden /></IconButton>
                      <IconButton label={t('Export .sdd')} onClick={() => actions.export(p.id)}><Download size={14} aria-hidden /></IconButton>
                      <IconButton label={t('Delete')} className="danger-icon" onClick={() => void remove(p.id)}><Trash2 size={14} aria-hidden /></IconButton>
                    </div>
                  </div>
                </motion.li>
              ))}
            </ul>
          )}
          {list.length > 0 && visible.length === 0 && <EmptyState title={t('No matching projects')} hint={t('Nothing matches “{query}”.', { query })} />}
        </motion.section>
        <p className="drop-hint" aria-label={t('Drop a .sdd file here')}><FileUp size={14} aria-hidden /> {t('Drag a')} <code>.sdd</code> {t('file anywhere on this page to open it.')}</p>
      </div>
      {menu && (
        <ContextMenuView
          x={menu.x}
          y={menu.y}
          items={getMenuItems({ type: 'project', id: menu.id }, { nodes: [], edges: [], hasClipboard: false, hasStyleClip: false, pageCount: 1, canRename: canRename(menu.id) })}
          onClose={() => setMenu(null)}
          onRun={(a) => { executeAction(a, { projectId: menu.id, project: actions }); setMenu(null); }}
        />
      )}
    </main>
  );
}
