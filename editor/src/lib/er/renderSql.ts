// scope follows internal/ddl/render.go (Script), extended to indexes, checks and enums.
import type { Dialect, ErColumnDef, ErSchemaDef, ErTableDef } from './types';

export const q = (d: Dialect, s: string): string => (d === 'mysql' ? `\`${s.replace(/`/g, '``')}\`` : `"${s.replace(/"/g, '""')}"`);
const isExpr = (s: string) => /[()\s]/.test(s);
const qcol = (d: Dialect, s: string) => (isExpr(s) ? s : q(d, s));
export const qtable = (d: Dialect, t: Pick<ErTableDef, 'schema' | 'name'>) => (t.schema && d !== 'sqlite' ? `${q(d, t.schema)}.${q(d, t.name)}` : q(d, t.name));

const INT_RE = /^(int|integer|bigint|smallint|tinyint|mediumint|serial|bigserial|smallserial)\b/i;

/** map a type spelled for any dialect onto the target dialect */
export function mapType(type: string, d: Dialect, c?: Pick<ErColumnDef, 'generated'>): string {
  const t = type.trim();
  const l = t.toLowerCase();
  const auto = !!c?.generated && (c.generated === 'autoincrement' || c.generated === 'identity');
  if (d === 'postgres') {
    if (/^tinyint\(1\)$/.test(l)) return 'boolean';
    if (/^(tinyint|mediumint)/.test(l)) return 'smallint';
    if (/^datetime/.test(l)) return 'timestamp';
    if (/^(longtext|mediumtext|tinytext)$/.test(l)) return 'text';
    if (/^(longblob|blob|mediumblob)$/.test(l)) return 'bytea';
    if (/^double$/.test(l)) return 'double precision';
    if (/^enum\(/.test(l)) return 'text';
    return t.replace(/\s+unsigned/i, '');
  }
  if (d === 'mysql') {
    if (/^(serial)$/.test(l)) return 'int';
    if (/^bigserial$/.test(l)) return 'bigint';
    if (/^smallserial$/.test(l)) return 'smallint';
    if (/^uuid$/.test(l)) return 'char(36)';
    if (/^(timestamptz|timestamp with time zone)$/.test(l)) return 'timestamp';
    if (/^timestamp without time zone$/.test(l)) return 'timestamp';
    if (/^(jsonb)$/.test(l)) return 'json';
    if (/^bytea$/.test(l)) return 'blob';
    if (/^(text|character varying)$/.test(l) && l === 'character varying') return 'varchar(255)';
    if (/^character varying\((\d+)\)$/.test(l)) return t.replace(/character varying/i, 'varchar');
    if (/^double precision$/.test(l)) return 'double';
    if (/\[\]$/.test(l)) return 'json';
    if (/^varchar$/.test(l)) return 'varchar(255)';
    return t;
  }
  // sqlite: affinity-friendly names
  if (auto && INT_RE.test(l)) return 'INTEGER';
  if (/^(serial|bigserial|smallserial)$/.test(l)) return 'INTEGER';
  if (/^uuid$/.test(l)) return 'TEXT';
  if (/^(timestamptz|timestamp.*|datetime.*)$/.test(l)) return 'DATETIME';
  if (/^jsonb?$/.test(l)) return 'TEXT';
  if (/\[\]$/.test(l)) return 'TEXT';
  if (/^enum\(/.test(l)) return 'TEXT';
  return t.replace(/\s+unsigned/i, '');
}

export function columnSql(d: Dialect, c: ErColumnDef, soloPk: boolean): string {
  const parts = [q(d, c.name)];
  let type = mapType(c.type || 'text', d, c);
  const auto = c.generated === 'autoincrement' || c.generated === 'identity';
  if (d === 'postgres' && auto && INT_RE.test(type) && !/serial/i.test(type)) type = type.replace(/\s.*$/, '');
  parts.push(type);
  if (d === 'sqlite' && soloPk && auto && /integer/i.test(type)) {
    parts.push('PRIMARY KEY AUTOINCREMENT');
    return parts.join(' ');
  }
  if (c.generated?.startsWith('as ')) parts.push(d === 'postgres' ? `GENERATED ALWAYS ${c.generated} STORED` : `GENERATED ALWAYS ${c.generated}`);
  else if (auto) {
    if (d === 'postgres' && !/serial/i.test(c.type)) parts.push('GENERATED BY DEFAULT AS IDENTITY');
    else if (d === 'mysql') parts.push('AUTO_INCREMENT');
  }
  if (!c.nullable || c.pk) parts.push('NOT NULL');
  if (c.default !== undefined && !(d === 'postgres' && /^nextval\(/i.test(c.default) && auto)) parts.push(`DEFAULT ${c.default}`);
  if (c.unique && !c.pk) parts.push('UNIQUE');
  if (d === 'mysql' && c.comment) parts.push(`COMMENT '${c.comment.replace(/'/g, "''")}'`);
  return parts.join(' ');
}

/** CREATE TABLE (+ indexes) for one table */
export function tableSql(d: Dialect, t: ErTableDef, schema: ErSchemaDef): string[] {
  const pks = t.columns.filter((c) => c.pk);
  const solo = pks.length === 1;
  const lines: string[] = t.columns.map((c) => '  ' + columnSql(d, c, solo));
  const sqliteInlinePk = d === 'sqlite' && solo && (pks[0].generated === 'autoincrement' || pks[0].generated === 'identity') && /int/i.test(pks[0].type);
  if (pks.length && !sqliteInlinePk) lines.push(`  PRIMARY KEY (${pks.map((c) => q(d, c.name)).join(', ')})`);
  const groups = new Map<string, ErColumnDef[]>();
  for (const c of t.columns) if (c.fk) {
    const k = c.fk.group ? `g:${c.fk.group}` : `c:${c.name}`;
    groups.set(k, [...(groups.get(k) ?? []), c]);
  }
  for (const cols of groups.values()) {
    const fk = cols[0].fk!;
    const parent = schema.tables.find((x) => x.name === fk.table);
    const refCols = cols.map((c) => c.fk!.column || parent?.columns.find((x) => x.pk)?.name || 'id');
    let s = `  ${fk.name ? `CONSTRAINT ${q(d, fk.name)} ` : ''}FOREIGN KEY (${cols.map((c) => q(d, c.name)).join(', ')}) REFERENCES ${qtable(d, parent ?? { name: fk.table })} (${refCols.map((x) => q(d, x)).join(', ')})`;
    if (fk.onDelete) s += ` ON DELETE ${fk.onDelete}`;
    if (fk.onUpdate) s += ` ON UPDATE ${fk.onUpdate}`;
    lines.push(s);
  }
  for (const ch of t.checks) lines.push(`  ${ch.name ? `CONSTRAINT ${q(d, ch.name)} ` : ''}CHECK (${ch.expr})`);
  const uniques = t.indexes.filter((i) => i.unique && !i.where && !i.using && i.columns.every((c) => !isExpr(c)));
  for (const u of uniques) lines.push(`  ${u.name ? `CONSTRAINT ${q(d, u.name)} ` : ''}UNIQUE (${u.columns.map((c) => q(d, c)).join(', ')})`);
  const out = [`CREATE TABLE ${qtable(d, t)} (\n${lines.join(',\n')}\n)${d === 'mysql' ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4' : ''};`];
  for (const i of t.indexes) {
    if (uniques.includes(i)) continue;
    const name = i.name ?? `idx_${t.name}_${i.columns.join('_').replace(/[^A-Za-z0-9_]+/g, '')}`;
    out.push(`CREATE ${i.unique ? 'UNIQUE ' : ''}INDEX ${q(d, name)} ON ${qtable(d, t)}${d === 'postgres' && i.using ? ` USING ${i.using}` : ''} (${i.columns.map((c) => qcol(d, c)).join(', ')})${i.where && d !== 'mysql' ? ` WHERE ${i.where}` : ''};`);
  }
  if (d === 'postgres') {
    if (t.comment) out.push(`COMMENT ON TABLE ${qtable(d, t)} IS '${t.comment.replace(/'/g, "''")}';`);
    for (const c of t.columns) if (c.comment) out.push(`COMMENT ON COLUMN ${qtable(d, t)}.${q(d, c.name)} IS '${c.comment.replace(/'/g, "''")}';`);
  }
  return out;
}

/** Parents before children; cycles fall back to input order. */
export function orderTables(tables: ErTableDef[]): ErTableDef[] {
  const out: ErTableDef[] = [];
  const state = new Map<string, number>();
  const by = new Map(tables.map((t) => [t.name, t]));
  const visit = (t: ErTableDef) => {
    if (state.get(t.name)) return;
    state.set(t.name, 1);
    for (const c of t.columns) {
      const p = c.fk && c.fk.table !== t.name ? by.get(c.fk.table) : undefined;
      if (p) visit(p);
    }
    out.push(t);
  };
  tables.forEach(visit);
  return out;
}

export function renderSql(schema: ErSchemaDef, d: Dialect): string {
  const out: string[] = [`-- Generated by System Design Diagram (${d})`];
  if (d === 'postgres')
    for (const e of schema.enums) out.push(`CREATE TYPE ${q(d, e.name)} AS ENUM (${e.values.map((v) => `'${v.replace(/'/g, "''")}'`).join(', ')});`);
  const tables = schema.tables.filter((t) => t.kind !== 'view');
  for (const t of orderTables(tables)) out.push('', ...tableSql(d, t, schema));
  for (const v of schema.tables.filter((t) => t.kind === 'view'))
    out.push('', `CREATE VIEW ${qtable(d, v)} AS SELECT ${v.columns.length ? v.columns.map((c) => q(d, c.name)).join(', ') : '*'} FROM ${q(d, 'source')};`);
  return out.join('\n') + '\n';
}
