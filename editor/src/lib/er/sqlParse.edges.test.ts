import { describe, expect, it } from 'vitest';
import { detectDialect, parseSql, stripDownMigrations, tokenize } from './sqlParse';
import { findTable } from './types';

const parse = (sql: string) => parseSql(sql);
const table = (sql: string, name: string) => findTable(parse(sql).schema, name);

describe('tokenize edge cases', () => {
  it('hash comments only at line start; # operators stay', () => {
    expect(tokenize('# note\nSELECT 1').map((t) => t.v)).toEqual(['SELECT', '1']);
    expect(tokenize('a #> b').some((t) => t.v === '#')).toBe(true);
    expect(tokenize('a # b').some((t) => t.v === '#')).toBe(true);
  });
  it('bracket identifiers, array brackets, numbers', () => {
    expect(tokenize('[dbo] [1]').map((t) => t.v)).toContain('dbo');
    expect(tokenize('int[]').map((t) => t.v)).toEqual(['int', '[', ']']);
    expect(tokenize('.5 1e+3 7').map((t) => t.v)).toEqual(['.5', '1e+3', '7']);
    expect(tokenize('1 . x').length).toBeGreaterThan(1);
  });
});

describe('column modifiers', () => {
  it('KEY, IDENTITY, GENERATED ALWAYS/BY DEFAULT AS IDENTITY / AS (expr), AS (expr)', () => {
    const sql = `CREATE TABLE t (
      a int PRIMARY KEY, b int NOT NULL UNIQUE KEY,
      c int IDENTITY(1,1), d int IDENTITY,
      e int GENERATED ALWAYS AS IDENTITY,
      f int GENERATED BY DEFAULT AS IDENTITY (START WITH 5),
      g int GENERATED ALWAYS AS (a + 1) STORED,
      h int AS (a * 2) VIRTUAL,
      i int GENERATED ALWAYS,
      j varchar(10) CHARACTER SET utf8 COLLATE utf8_bin COMMENT 'x',
      k varchar(10) CHARACTER latin1,
      l timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      m timestamp ON UPDATE now() ,
      n int DEFAULT 5 CHECK (n > 0) REFERENCES other(id) ON DELETE CASCADE,
      o int unsigned zerofill,
      p int AUTO_INCREMENT
    );`;
    const t = table(sql, 't')!;
    expect(t.columns.map((c) => c.name)).toEqual(['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i', 'j', 'k', 'l', 'm', 'n', 'o', 'p']);
    expect(t.columns.find((c) => c.name === 'c')?.generated).toBe('identity');
    expect(t.columns.find((c) => c.name === 'a')?.pk).toBe(true);
  });
  it('type then unknown keyword stops before a constraint keyword', () => {
    const t = table('CREATE TABLE t (a double precision CONSTRAINT nn NOT NULL, b numeric(10,2) COLLATE "C", c int CHECK (c>1) UNIQUE)', 't')!;
    expect(t.columns).toHaveLength(3);
    expect(t.columns[0].nullable).toBe(false);
  });
  it('a non-word token in a column list is skipped', () => {
    const t = table('CREATE TABLE t (a int 5 , b int)', 't');
    expect(t?.columns.map((c) => c.name)).toContain('b');
  });
});

describe('table constraints and options', () => {
  it('composite FK with names, MATCH, ON actions; USING index types; KEY forms', () => {
    const sql = `CREATE TABLE p (id int, id2 int, PRIMARY KEY (id, id2));
    CREATE TABLE c (
      a int, b int, x int,
      CONSTRAINT fk_ab FOREIGN KEY (a, b) REFERENCES p (id, id2) ON DELETE SET NULL ON UPDATE CASCADE,
      FOREIGN KEY (x) REFERENCES p,
      UNIQUE KEY uk (a), UNIQUE INDEX (b), KEY ix USING BTREE (a), INDEX (b) USING HASH,
      FULLTEXT KEY ft (x), CHECK (a > 0), CONSTRAINT ck CHECK (b > 0),
      EXCLUDE USING gist (a WITH =)
    );`;
    const r = parse(sql);
    const c = findTable(r.schema, 'c')!;
    expect(c.columns.find((x) => x.name === 'a')?.fk).toMatchObject({ name: 'fk_ab' });
    expect(c.indexes.length).toBeGreaterThan(0);
    expect(c.checks.length).toBeGreaterThan(0);
  });
  it('INHERITS unknown / known, LIKE unknown / known, PARTITION and trailing options', () => {
    const r = parse(`CREATE TABLE base (id int, n text);
      CREATE TABLE child (x int) INHERITS (base);
      CREATE TABLE orphan (x int) INHERITS (nope.missing);
      CREATE TABLE copy (LIKE base INCLUDING ALL, extra int);
      CREATE TABLE copy2 (LIKE ghost);
      CREATE TABLE opt (a int) ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='x';
      CREATE TABLE IF NOT EXISTS ine (a int);
      CREATE TEMP TABLE tmp (a int);
      CREATE UNLOGGED TABLE ul (a int);`);
    expect(r.warnings.some((w) => w.includes('INHERITS unknown'))).toBe(true);
    expect(r.warnings.some((w) => w.includes('LIKE unknown'))).toBe(true);
    expect(findTable(r.schema, 'child')?.columns.map((c) => c.name)).toContain('id');
    expect(findTable(r.schema, 'copy')?.columns.map((c) => c.name)).toEqual(expect.arrayContaining(['id', 'extra']));
    expect(findTable(r.schema, 'ine')).toBeTruthy();
  });
  it('empty list items are tolerated', () => {
    expect(table('CREATE TABLE t (a int,, b int,)', 't')?.columns.length).toBeGreaterThanOrEqual(2);
  });
});

describe('ALTER TABLE', () => {
  const base = 'CREATE TABLE t (id int PRIMARY KEY, name varchar(5) NOT NULL DEFAULT \'x\', n int, "Mixed" int);\nCREATE INDEX t_ix ON t (name);\nALTER TABLE t ADD CONSTRAINT ck CHECK (n > 0);\n';
  it('ALTER COLUMN: SET/DROP NOT NULL, SET/DROP DEFAULT, TYPE, SET DATA TYPE, unknown column', () => {
    const r = parse(`${base}
      ALTER TABLE t ALTER COLUMN name DROP NOT NULL;
      ALTER TABLE t ALTER COLUMN n SET NOT NULL;
      ALTER TABLE t ALTER COLUMN name DROP DEFAULT;
      ALTER TABLE t ALTER COLUMN n SET DEFAULT 7;
      ALTER TABLE t ALTER COLUMN n TYPE bigint;
      ALTER TABLE t ALTER n SET DATA TYPE smallint;
      ALTER TABLE t ALTER COLUMN ghost SET NOT NULL;
      ALTER TABLE t ALTER COLUMN mixed SET NOT NULL;`);
    const t = findTable(r.schema, 't')!;
    expect(t.columns.find((c) => c.name === 'name')?.nullable).toBe(true);
    expect(t.columns.find((c) => c.name === 'name')?.default).toBeUndefined();
    expect(t.columns.find((c) => c.name === 'n')?.default).toBe('7');
    expect(t.columns.find((c) => c.name === 'n')?.type).toBe('smallint');
    expect(t.columns.find((c) => c.name === 'Mixed')?.nullable).toBe(false);
  });
  it('MODIFY / CHANGE COLUMN with and without COLUMN keyword; unknown old column', () => {
    const r = parse(`${base}
      ALTER TABLE t MODIFY COLUMN n varchar(9) NOT NULL;
      ALTER TABLE t MODIFY name text;
      ALTER TABLE t CHANGE COLUMN n n2 bigint;
      ALTER TABLE t CHANGE ghost g2 int;`);
    const t = findTable(r.schema, 't')!;
    expect(t.columns.some((c) => c.name === 'n2')).toBe(true);
  });
  it('RENAME COLUMN / TO, rename constraint, rename index, rename table', () => {
    const r = parse(`${base}
      ALTER TABLE t RENAME COLUMN name TO title;
      ALTER TABLE t RENAME COLUMN ghost TO nothing;
      ALTER TABLE t RENAME CONSTRAINT ck TO ck2;
      ALTER INDEX t_ix RENAME TO t_ix2;
      ALTER TABLE t RENAME TO t2;`);
    const t = findTable(r.schema, 't2')!;
    expect(t).toBeTruthy();
    expect(t.columns.some((c) => c.name === 'title')).toBe(true);
    expect(t.indexes.some((i) => i.name === 't_ix2')).toBe(true);
    expect(t.indexes.find((i) => i.name === 't_ix2')?.columns).toEqual(['title']);
  });
  it('ADD / DROP column and constraint, unknown table', () => {
    const r = parse(`${base}
      ALTER TABLE t ADD COLUMN extra int;
      ALTER TABLE t ADD extra2 int;
      ALTER TABLE t DROP COLUMN n;
      ALTER TABLE t DROP CONSTRAINT ck;
      ALTER TABLE nope ADD COLUMN z int;
      ALTER TABLE t ADD FOREIGN KEY (id) REFERENCES t (id);`);
    const t = findTable(r.schema, 't')!;
    expect(t.columns.some((c) => c.name === 'extra')).toBe(true);
    expect(t.columns.some((c) => c.name === 'n')).toBe(false);
  });
});

describe('views, types, misc', () => {
  it('CREATE VIEW: explicit columns, select aliases, stars skipped, IF NOT EXISTS, OR REPLACE, no select', () => {
    const r = parse(`CREATE TABLE a (id int, n int);
      CREATE VIEW v1 (x, y) AS SELECT id, n FROM a;
      CREATE OR REPLACE VIEW v2 AS SELECT id AS ident, a.n, count(*) total FROM a;
      CREATE VIEW v3 AS SELECT * FROM a;
      CREATE VIEW IF NOT EXISTS v4 AS SELECT id, FROM a;
      CREATE MATERIALIZED VIEW v5 AS SELECT id FROM a;
      CREATE VIEW v6 AS WITH q AS (SELECT 1) SELECT 1 AS one;
      CREATE VIEW;
      CREATE VIEW v7 AS VALUES (1);`);
    expect(findTable(r.schema, 'v1')?.columns.map((c) => c.name)).toEqual(['x', 'y']);
    expect(findTable(r.schema, 'v2')?.columns.map((c) => c.name)).toEqual(expect.arrayContaining(['ident']));
    expect(findTable(r.schema, 'v3')?.kind).toBe('view');
  });
  it('CREATE TYPE enums, OR REPLACE TYPE and non-enum types', () => {
    const r = parse(`CREATE TYPE mood AS ENUM ('a','b');
      CREATE TYPE pair AS (a int, b int);
      CREATE OR REPLACE TYPE other AS ENUM ('z');
      CREATE DOMAIN d AS int;`);
    expect(r.schema.enums.map((e) => e.name)).toContain('mood');
  });
  it('unknown statements and stray punctuation do not throw', () => {
    expect(() => parse('SELECT 1; ; ;;; INSERT INTO t VALUES (1); DROP TABLE x; GRANT ALL ON t TO u; BEGIN; COMMIT;')).not.toThrow();
    expect(() => parse('')).not.toThrow();
  });
  it('CREATE INDEX forms: unique, concurrently, IF NOT EXISTS, USING, expressions, unknown table', () => {
    const r = parse(`CREATE TABLE t (a int, b int);
      CREATE UNIQUE INDEX i1 ON t (a, b);
      CREATE INDEX CONCURRENTLY IF NOT EXISTS i2 ON t USING btree (a DESC NULLS LAST);
      CREATE INDEX i3 ON t ((lower(a::text)));
      CREATE INDEX i4 ON ghost (a);
      CREATE INDEX ON t (b);`);
    expect(findTable(r.schema, 't')!.indexes.length).toBeGreaterThanOrEqual(3);
  });
  it('COMMENT ON TABLE / COLUMN', () => {
    const t = table(`CREATE TABLE t (a int); COMMENT ON TABLE t IS 'tbl'; COMMENT ON COLUMN t.a IS 'col'; COMMENT ON COLUMN ghost.a IS 'x';`, 't')!;
    expect(t.columns[0].comment ?? t.comment).toBeTruthy();
  });
});

describe('dialect and migrations', () => {
  it('detects dialects', () => {
    expect(detectDialect('CREATE TABLE `a` (id int AUTO_INCREMENT) ENGINE=InnoDB')).toBe('mysql');
    expect(detectDialect('CREATE TABLE a (id serial); CREATE TYPE x AS ENUM (\'a\')')).toBe('postgres');
    expect(detectDialect('CREATE TABLE a (id integer PRIMARY KEY AUTOINCREMENT)')).toBe('sqlite');
    expect(detectDialect('CREATE TABLE a (id int)')).toBeTruthy();
  });
  it('stripDownMigrations keeps the up part of goose/dbmate/migrate styles', () => {
    expect(stripDownMigrations('-- +goose Up\nCREATE TABLE a (id int);\n-- +goose Down\nDROP TABLE a;')).not.toContain('DROP TABLE');
    expect(stripDownMigrations('-- migrate:up\nCREATE TABLE a (id int);\n-- migrate:down\nDROP TABLE a;')).not.toContain('DROP TABLE');
    expect(stripDownMigrations('CREATE TABLE a (id int);')).toContain('CREATE TABLE');
    expect(stripDownMigrations('-- +migrate Down\nDROP TABLE a;')).not.toContain('DROP');
  });
});
