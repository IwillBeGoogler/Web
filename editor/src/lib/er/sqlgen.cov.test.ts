import { describe, expect, it } from 'vitest';
import { columnSql, mapType, orderTables, q, qtable, renderSql, tableSql } from './renderSql';
import { migrationSql } from './migrate';
import { looksLikeSeedora, parseSeedora, renderSeedora } from './seedora';
import { emptySchema, newColumn, newTable, type ErSchemaDef } from './types';

const sch = (...tables: ReturnType<typeof newTable>[]): ErSchemaDef => ({ ...emptySchema(), tables });
const c = newColumn;

describe('mapType', () => {
  it('postgres maps mysql-isms', () => {
    expect(mapType('tinyint(1)', 'postgres')).toBe('boolean');
    expect(mapType('tinyint', 'postgres')).toBe('smallint');
    expect(mapType('mediumint(8)', 'postgres')).toBe('smallint');
    expect(mapType('datetime(6)', 'postgres')).toBe('timestamp');
    expect(mapType('LONGTEXT', 'postgres')).toBe('text');
    expect(mapType('blob', 'postgres')).toBe('bytea');
    expect(mapType('double', 'postgres')).toBe('double precision');
    expect(mapType("enum('a','b')", 'postgres')).toBe('text');
    expect(mapType('int unsigned', 'postgres')).toBe('int');
  });
  it('mysql maps postgres-isms', () => {
    const m = (t: string) => mapType(t, 'mysql');
    expect(m('serial')).toBe('int');
    expect(m('bigserial')).toBe('bigint');
    expect(m('smallserial')).toBe('smallint');
    expect(m('uuid')).toBe('char(36)');
    expect(m('timestamptz')).toBe('timestamp');
    expect(m('timestamp without time zone')).toBe('timestamp');
    expect(m('jsonb')).toBe('json');
    expect(m('bytea')).toBe('blob');
    expect(m('character varying')).toBe('varchar(255)');
    expect(m('character varying(20)')).toBe('varchar(20)');
    expect(m('double precision')).toBe('double');
    expect(m('text[]')).toBe('json');
    expect(m('varchar')).toBe('varchar(255)');
    expect(m('text')).toBe('text');
  });
  it('sqlite maps to affinity names', () => {
    const m = (t: string, g?: string) => mapType(t, 'sqlite', { generated: g });
    expect(m('bigint', 'autoincrement')).toBe('INTEGER');
    expect(m('int', 'identity')).toBe('INTEGER');
    expect(m('int', 'as (x)')).toBe('int');
    expect(m('serial')).toBe('INTEGER');
    expect(m('uuid')).toBe('TEXT');
    expect(m('timestamptz')).toBe('DATETIME');
    expect(m('datetime(3)')).toBe('DATETIME');
    expect(m('jsonb')).toBe('TEXT');
    expect(m('int[]')).toBe('TEXT');
    expect(m("enum('a')")).toBe('TEXT');
    expect(m('int unsigned')).toBe('int');
    expect(mapType('serial', 'sqlite')).toBe('INTEGER');
  });
});

describe('columnSql', () => {
  it('postgres: identity, serial, generated, default, unique', () => {
    expect(columnSql('postgres', c('id', 'bigint', { pk: true, nullable: false, generated: 'autoincrement' }), true)).toBe('"id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(columnSql('postgres', c('id', 'serial', { pk: true, generated: 'autoincrement' }), true)).toBe('"id" serial NOT NULL');
    expect(columnSql('postgres', c('id', 'int unsigned', { generated: 'identity' }), false)).toBe('"id" int GENERATED BY DEFAULT AS IDENTITY');
    expect(columnSql('postgres', c('t', 'int', { generated: 'as (a+b)' }), false)).toBe('"t" int GENERATED ALWAYS as (a+b) STORED');
    expect(columnSql('postgres', c('n', 'int', { generated: 'autoincrement', default: "nextval('s')" }), false)).toBe('"n" int GENERATED BY DEFAULT AS IDENTITY');
    expect(columnSql('postgres', c('n', 'text', { default: "'x'", unique: true, nullable: false }), false)).toBe('"n" text NOT NULL DEFAULT \'x\' UNIQUE');
  });
  it('mysql: auto_increment, generated, comment with quote escaping', () => {
    expect(columnSql('mysql', c('id', 'int', { pk: true, generated: 'autoincrement' }), true)).toBe('`id` int AUTO_INCREMENT NOT NULL');
    expect(columnSql('mysql', c('t', 'int', { generated: 'as (1)' }), false)).toBe('`t` int GENERATED ALWAYS as (1)');
    expect(columnSql('mysql', c('n', 'text', { comment: "it's" }), false)).toBe("`n` text COMMENT 'it''s'");
  });
  it('sqlite: inline PRIMARY KEY AUTOINCREMENT only for a solo integer pk', () => {
    expect(columnSql('sqlite', c('id', 'int', { pk: true, generated: 'autoincrement' }), true)).toBe('"id" INTEGER PRIMARY KEY AUTOINCREMENT');
    expect(columnSql('sqlite', c('id', 'int', { pk: true, generated: 'autoincrement' }), false)).toBe('"id" INTEGER NOT NULL');
    expect(columnSql('sqlite', c('x', ''), false)).toBe('"x" text');
  });
  it('quoting escapes the quote char', () => {
    expect(q('postgres', 'a"b')).toBe('"a""b"');
    expect(q('mysql', 'a`b')).toBe('`a``b`');
    expect(qtable('sqlite', { schema: 's', name: 't' })).toBe('"t"');
    expect(qtable('postgres', { schema: 's', name: 't' })).toBe('"s"."t"');
  });
});

describe('tableSql / renderSql', () => {
  const parent = newTable('users', [c('id', 'int', { pk: true, nullable: false })], { schema: 'app', comment: "it's" });
  const child = newTable(
    'orders',
    [
      c('id', 'int', { pk: true, nullable: false }),
      c('user_id', 'int', { fk: { table: 'users', column: '', onDelete: 'CASCADE', onUpdate: 'SET NULL', name: 'fk_u' } }),
      c('a', 'int', { fk: { table: 'pairs', column: 'a', group: 'g' } }),
      c('b', 'int', { fk: { table: 'pairs', column: 'b', group: 'g' } }),
      c('ghost', 'int', { fk: { table: 'nowhere', column: '' } }),
      c('note', 'text', { comment: "a'b" }),
    ],
    {
      checks: [{ name: 'ck', expr: 'id > 0' }, { expr: 'id < 9' }],
      indexes: [
        { name: 'uq1', columns: ['note'], unique: true },
        { columns: ['note', 'id'], unique: false },
        { columns: ['lower(note)'], unique: true, where: 'id > 1' },
        { name: 'gin1', columns: ['note'], unique: false, using: 'gin' },
      ],
    },
  );
  it('emits pk, fks (single + composite), checks, uniques, indexes, comments (postgres)', () => {
    const sql = tableSql('postgres', child, sch(parent, child)).join('\n');
    expect(sql).toContain('PRIMARY KEY ("id")');
    expect(sql).toContain('CONSTRAINT "fk_u" FOREIGN KEY ("user_id") REFERENCES "app"."users" ("id") ON DELETE CASCADE ON UPDATE SET NULL');
    expect(sql).toContain('FOREIGN KEY ("a", "b") REFERENCES "pairs" ("a", "b")');
    expect(sql).toContain('FOREIGN KEY ("ghost") REFERENCES "nowhere" ("id")');
    expect(sql).toContain('CONSTRAINT "ck" CHECK (id > 0)');
    expect(sql).toContain('  CHECK (id < 9)');
    expect(sql).toContain('CONSTRAINT "uq1" UNIQUE ("note")');
    expect(sql).toContain('CREATE INDEX "idx_orders_note_id" ON "orders" ("note", "id");');
    expect(sql).toContain('CREATE UNIQUE INDEX "idx_orders_lowernote" ON "orders" (lower(note)) WHERE id > 1;');
    expect(sql).toContain('CREATE INDEX "gin1" ON "orders" USING gin ("note");');
    expect(sql).toContain(`COMMENT ON COLUMN "orders"."note" IS 'a''b';`);
    expect(tableSql('postgres', parent, sch(parent)).join('\n')).toContain(`COMMENT ON TABLE "app"."users" IS 'it''s';`);
  });
  it('mysql: engine suffix and no WHERE / USING', () => {
    const sql = tableSql('mysql', child, sch(parent, child)).join('\n');
    expect(sql).toContain('ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;');
    expect(sql).not.toContain('WHERE');
    expect(sql).not.toContain('USING');
    expect(sql).not.toContain('COMMENT ON');
  });
  it('sqlite inline autoincrement pk omits PRIMARY KEY clause', () => {
    const t = newTable('t', [c('id', 'integer', { pk: true, generated: 'autoincrement' })]);
    const sql = tableSql('sqlite', t, sch(t))[0];
    expect(sql).toContain('PRIMARY KEY AUTOINCREMENT');
    expect(sql.match(/PRIMARY KEY/g)).toHaveLength(1);
  });
  it('orderTables puts parents first, tolerates self refs and cycles', () => {
    const a = newTable('a', [c('id'), c('b_id', 'int', { fk: { table: 'b', column: 'id' } })]);
    const b = newTable('b', [c('id'), c('a_id', 'int', { fk: { table: 'a', column: 'id' } }), c('me', 'int', { fk: { table: 'b', column: 'id' } })]);
    const p = newTable('p', [c('id')]);
    const k = newTable('k', [c('p', 'int', { fk: { table: 'p', column: 'id' } })]);
    expect(orderTables([k, p]).map((t) => t.name)).toEqual(['p', 'k']);
    expect(orderTables([a, b]).map((t) => t.name).sort()).toEqual(['a', 'b']);
  });
  it('renderSql: header, enums (postgres only), views, view without columns', () => {
    const s = sch(parent, newTable('v1', [c('x')], { kind: 'view' }), newTable('v2', [], { kind: 'view' }));
    s.enums.push({ name: 'mood', values: ["o'k", 'sad'] });
    const pg = renderSql(s, 'postgres');
    expect(pg.startsWith('-- Generated by System Design Diagram (postgres)')).toBe(true);
    expect(pg).toContain(`CREATE TYPE "mood" AS ENUM ('o''k', 'sad');`);
    expect(pg).toContain('CREATE VIEW "v1" AS SELECT "x" FROM "source";');
    expect(pg).toContain('CREATE VIEW "v2" AS SELECT * FROM "source";');
    expect(renderSql(s, 'mysql')).not.toContain('CREATE TYPE');
  });
});

describe('migrationSql', () => {
  const t = (name: string, cols: ReturnType<typeof newColumn>[]) => newTable(name, cols);
  const before = sch(t('keep', [c('id', 'int', { pk: true, nullable: false }), c('a', 'int'), c('gone', 'int'), c('f', 'int', { fk: { table: 'x', column: 'id' } })]), t('dropme', [c('id')]));
  const after = sch(
    t('keep', [c('id', 'int', { pk: true, nullable: false }), c('a', 'bigint', { nullable: false, default: '1' }), c('f', 'int', { fk: { table: 'y', column: 'id', onDelete: 'CASCADE', onUpdate: 'RESTRICT' } }), c('n', 'text', { fk: { table: 'x', column: '', name: 'fk_n' } })]),
    t('fresh', [c('id')]),
  );
  it('no changes', () => {
    expect(migrationSql(before, before, 'postgres')).toBe('-- no changes');
  });
  it('postgres: create/alter/drop', () => {
    const sql = migrationSql(before, after, 'postgres');
    expect(sql).toContain('CREATE TABLE "fresh"');
    expect(sql).toContain('ALTER TABLE "keep" ALTER COLUMN "a" TYPE bigint;');
    expect(sql).toContain('ALTER TABLE "keep" ALTER COLUMN "a" SET NOT NULL;');
    expect(sql).toContain('ALTER TABLE "keep" ALTER COLUMN "a" SET DEFAULT 1;');
    expect(sql).toContain('ALTER TABLE "keep" DROP CONSTRAINT "fk_keep_f";');
    expect(sql).toContain('ADD CONSTRAINT "fk_keep_f" FOREIGN KEY ("f") REFERENCES "y" ("id") ON DELETE CASCADE ON UPDATE RESTRICT;');
    expect(sql).toContain('ADD COLUMN "n" text;');
    expect(sql).toContain('ADD CONSTRAINT "fk_n" FOREIGN KEY ("n") REFERENCES "x" ("id");');
    expect(sql).toContain('ALTER TABLE "keep" DROP COLUMN "gone";');
    expect(sql).toContain('DROP TABLE "dropme";');
  });
  it('postgres: drop nullability and defaults', () => {
    const b = sch(t('t', [c('a', 'int', { nullable: false, default: '1' })]));
    const a = sch(t('t', [c('a', 'int')]));
    const sql = migrationSql(b, a, 'postgres');
    expect(sql).toContain('ALTER COLUMN "a" DROP NOT NULL;');
    expect(sql).toContain('ALTER COLUMN "a" DROP DEFAULT;');
  });
  it('mysql: MODIFY COLUMN and DROP FOREIGN KEY', () => {
    const sql = migrationSql(before, after, 'mysql');
    expect(sql).toContain('ALTER TABLE `keep` MODIFY COLUMN `a` bigint NOT NULL DEFAULT 1;');
    expect(sql).toContain('ALTER TABLE `keep` DROP FOREIGN KEY `fk_keep_f`;');
  });
  it('sqlite: comments for what it cannot do', () => {
    const sql = migrationSql(before, after, 'sqlite');
    expect(sql).toContain('-- SQLite cannot alter column "a" in place: rebuild "keep"');
    expect(sql).toContain('-- SQLite cannot drop foreign key on "f": rebuild "keep"');
    expect(sql).toContain('-- SQLite cannot add foreign key on "f": rebuild "keep"');
    expect(migrationSql(before, before, 'sqlite')).toBe('-- no changes');
  });
  it('pk column nullability change is ignored', () => {
    const b = sch(t('t', [c('id', 'int', { pk: true, nullable: true })]));
    const a = sch(t('t', [c('id', 'int', { pk: true, nullable: false })]));
    expect(migrationSql(b, a, 'postgres')).toBe('-- no changes');
  });
});

describe('seedora', () => {
  it('looksLikeSeedora', () => {
    expect(looksLikeSeedora({ tables: [{ name: 'a' }] })).toBe(true);
    expect(looksLikeSeedora({ tables: [{ nom: 'a' }] })).toBe(false);
    expect(looksLikeSeedora([])).toBe(false);
    expect(looksLikeSeedora(null)).toBe(false);
  });
  it('parse errors', () => {
    expect(parseSeedora('{nope').warnings).toEqual(['Not valid JSON']);
    expect(parseSeedora({ x: 1 }).warnings[0]).toMatch(/Not a Seedora schema/);
  });
  it('parses tables, pk, unique, generated, defaults, fks, checks, enums, unknown refs', () => {
    const r = parseSeedora({
      tables: [
        {
          schema: 'app',
          name: 'a',
          primary_key: ['id'],
          columns: [
            { name: 'id', type: 'int', has_default: true, nullable: true },
            { name: 'u', native: ' varchar(9) ', unique: true },
            { name: 'g', type: 'int', generated: true },
            { name: 'd', type: 'text', has_default: true, nullable: false },
            { name: 'fk', type: 'int', fk: { table: 'zzz', column: 'id' } },
            { name: 'plain' },
          ],
          checks: [{ name: 'ck', expr: 'x' }, { expr: 'y' }],
        },
        { name: 'bare' },
      ],
      enums: { mood: ['a', 'b'] },
    });
    const a = r.schema.tables[0];
    expect(a.schema).toBe('app');
    expect(a.columns.map((x) => [x.pk, x.nullable, x.unique])).toEqual([[true, false, false], [false, true, true], [false, true, false], [false, false, false], [false, true, false], [false, true, false]]);
    expect(a.columns[0].generated).toBe('autoincrement');
    expect(a.columns[1].type).toBe('varchar(9)');
    expect(a.columns[2].generated).toBe('as ()');
    expect(a.columns[3].default).toBe('/* default */');
    expect(a.columns[5].type).toBe('text');
    expect(a.checks).toEqual([{ name: 'ck', expr: 'x' }, { expr: 'y' }]);
    expect(r.schema.tables[1].columns).toEqual([]);
    expect(r.schema.enums).toEqual([{ name: 'mood', values: ['a', 'b'] }]);
    expect(r.warnings).toEqual(['a.fk references unknown table zzz']);
  });
  it('a has_default pk of non-int type is just a default', () => {
    const r = parseSeedora({ tables: [{ name: 't', primary_key: ['id'], columns: [{ name: 'id', type: 'uuid', has_default: true }] }] });
    expect(r.schema.tables[0].columns[0].default).toBe('/* default */');
  });
  it('renderSeedora round-trips tables, drops views, includes checks and enums', () => {
    const s = sch(
      newTable('a', [c('id', 'varchar(10)', { pk: true, nullable: false, generated: 'identity' }), c('g', 'int', { generated: 'as (1)' }), c('b', 'int', { default: '3', unique: true, fk: { table: 'b', column: 'id' } })], { schema: 'app', checks: [{ expr: 'z' }, { name: 'n', expr: 'q' }] }),
      newTable('b', [c('id')]),
      newTable('v', [c('x')], { kind: 'view' }),
    );
    s.enums.push({ name: 'e', values: ['1'] });
    const j = JSON.parse(renderSeedora(s));
    expect(j.tables.map((t: { name: string }) => t.name)).toEqual(['a', 'b']);
    expect(j.tables[0].schema).toBe('app');
    expect(j.tables[0].columns[0]).toMatchObject({ type: 'varchar', native: 'varchar(10)', nullable: false, has_default: true, generated: false });
    expect(j.tables[0].columns[1].generated).toBe(true);
    expect(j.tables[0].columns[2]).toMatchObject({ has_default: true, unique: true, fk: { table: 'b', column: 'id' } });
    expect(j.tables[0].checks).toEqual([{ name: '', expr: 'z' }, { name: 'n', expr: 'q' }]);
    expect(j.tables[1].checks).toBeUndefined();
    expect(j.tables[1].schema).toBeUndefined();
    expect(j.enums).toEqual({ e: ['1'] });
    expect(JSON.parse(renderSeedora(sch())).enums).toBeUndefined();
  });
});
