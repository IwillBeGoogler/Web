import { describe, expect, it } from 'vitest';
import { detectDialect, parseSql, stripDownMigrations, tokenize } from './sqlParse';

const P = (sql: string) => parseSql(sql);
const T = (sql: string, name: string) => P(sql).schema.tables.find((t) => t.name === name)!;
const col = (sql: string, table: string, c: string) => T(sql, table).columns.find((x) => x.name === c)!;

describe('tokenize', () => {
  const kinds = (s: string) => tokenize(s).map((t) => `${t.k}:${t.v}`);
  it('drops comments, keeps strings, quoted identifiers and numbers', () => {
    expect(kinds("a -- c\n/* x */ 'it''s' \"q\"\"x\" `b``c` 1.5e3 .5 0xFF")).toEqual(['word:a', "str:it's", 'qident:q"x', 'qident:b`c', 'num:1.5e3', 'num:.5', 'num:0xFF']);
    expect(kinds('a /* unterminated')).toEqual(['word:a']);
  });
  it('# comments only at line start; # operators otherwise', () => {
    expect(kinds('# hash comment\nb')).toEqual(['word:b']);
    expect(kinds("a #> b")).toEqual(['word:a', 'punct:#', 'punct:>', 'word:b']);
    expect(kinds("x '#' #- y").length).toBeGreaterThan(2);
  });
  it('E-strings handle backslashes, N-strings, unterminated strings', () => {
    expect(kinds("E'a\\'b' N'x' e'\\n'")).toEqual(["str:a'b", 'str:x', 'str:n']);
    expect(kinds("'abc")).toEqual(['str:abc']);
  });
  it('bracket identifiers only where an identifier is expected', () => {
    expect(kinds('CREATE TABLE [my t] ([a b] int)')).toEqual(['word:CREATE', 'word:TABLE', 'qident:my t', 'punct:(', 'qident:a b', 'word:int', 'punct:)']);
    expect(kinds('int[] x')[1]).toBe('punct:[');
    expect(kinds('a[b] ')).toEqual(['word:a', 'punct:[', 'word:b', 'punct:]']);
    expect(kinds('TABLE [x')).toContain('punct:[');
    expect(kinds('TABLE [a,b]')).toContain('punct:[');
  });
  it('dollar quotes, operators and unicode identifiers', () => {
    expect(kinds('$$body$$ $tag$x$tag$ $ ')).toEqual(['str:body', 'str:x', 'punct:$']);
    expect(kinds('$$open')).toEqual(['str:open']);
    expect(kinds("a::b <> c -> d ->> e => f := g || h != i")).toEqual(['word:a', 'punct:::', 'word:b', 'punct:<>', 'word:c', 'punct:->', 'word:d', 'punct:->>', 'word:e', 'punct:=>', 'word:f', 'punct::=', 'word:g', 'punct:||', 'word:h', 'punct:!=', 'word:i']);
    expect(kinds('naïve')).toEqual(['word:naïve']);
    expect(kinds('1e+')[0]).toBe('num:1');
  });
});

describe('stripDownMigrations / detectDialect', () => {
  it('keeps up sections only, passes plain SQL through', () => {
    expect(stripDownMigrations('CREATE TABLE a (id int);')).toBe('CREATE TABLE a (id int);');
    expect(stripDownMigrations('-- migrate:up\nA;\n-- migrate:down\nB;\n-- +migrate Up\nC;')).not.toMatch(/B;/);
    expect(stripDownMigrations('X;\n-- +goose Up\nA;')).toContain('X;');
    expect(stripDownMigrations('-- +goose Down\nB;')).not.toContain('B;');
  });
  it('detectDialect', () => {
    expect(detectDialect('CREATE TABLE `a` (x int)')).toBe('mysql');
    expect(detectDialect('CREATE TABLE a (x int) ENGINE=InnoDB')).toBe('mysql');
    expect(detectDialect('CREATE TABLE a (x int unsigned)')).toBe('mysql');
    expect(detectDialect('CREATE TABLE a (x integer primary key autoincrement)')).toBe('sqlite');
    expect(detectDialect('PRAGMA foreign_keys=ON;')).toBe('sqlite');
    expect(detectDialect('CREATE TABLE a (x int) WITHOUT ROWID;')).toBe('sqlite');
    expect(detectDialect('CREATE TABLE a (x int);')).toBe('postgres');
    expect(P('CREATE TABLE `a` (x int);').dialect).toBe('mysql');
  });
});

