describe('CREATE VIEW', () => {
  it('uses an explicit column list or the select aliases; skips stars; replaces by name', () => {
    const r = P(`CREATE TABLE a (id int);
CREATE VIEW v1 (x, y) AS SELECT 1, 2;
CREATE OR REPLACE VIEW s.v2 AS SELECT id, count(*) AS n, a.id, * FROM a;
CREATE VIEW IF NOT EXISTS v3 AS SELECT 1 + 2 FROM a;
CREATE MATERIALIZED VIEW v4 AS SELECT id FROM a;
CREATE VIEW v5 SELECT id;
CREATE VIEW v1 (z) AS SELECT 1;
CREATE VIEW;`).schema;
    const v = (n: string) => r.tables.find((t) => t.name === n)!;
    expect(v('v1').columns.map((c) => c.name)).toEqual(['z']);
    expect(v('v1').kind).toBe('view');
    expect(v('v2').schema).toBe('s');
    expect(v('v2').columns.map((c) => c.name)).toEqual(['id', 'id']); // count(*) AS n is dropped: any item containing * is skipped
    expect(v('v3').columns).toEqual([]);
    expect(v('v4').columns.map((c) => c.name)).toEqual(['id']);
    expect(v('v5').columns.map((c) => c.name)).toEqual(['id']);
    expect(r.tables.filter((t) => t.name === 'v1')).toHaveLength(1);
  });
});

